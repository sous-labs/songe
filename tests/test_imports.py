"""songe import: an agent's own logs become recordings like the proxy's.

The log files are written by hand from each agent's documented format; no
real log is read and no model is loaded."""

import asyncio
import json

import pytest

from songe import cli, imports
from songe.reading import store as reading
from songe.reading import timeline
from tests.test_reading import FakeReader

T0 = "2026-11-01T10:00:00.000Z"


def jsonl(path, lines):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(json.dumps(line) + "\n" for line in lines), encoding="utf-8")
    return path


def cc(uuid, parent, kind, content, *, mid=None, model="claude-test", ts=T0, **extra):
    message = {"role": "assistant" if kind == "assistant" else "user", "content": content}
    if kind == "assistant":
        message |= {"id": mid, "model": model}
    line = {"type": kind, "uuid": uuid, "parentUuid": parent, "sessionId": "s1",
            "timestamp": ts, "isSidechain": False, "message": message}
    return line | extra


def claude_session(tmp_path, *, more=False):
    """Ask; one response runs the tests and reads a file in parallel; edit;
    done; the user corrects. Then a compaction, and one more request. Around
    it: a meta notice, a slash command, a subagent's turn, an API error the
    agent wrote itself and a branch the user rewound."""
    lines = [
        cc("u1", None, "user", "fix the failing test"),
        cc("meta", "u1", "user", "Caveat: The messages below were generated by the user while running local commands.", isMeta=True),
        cc("rewound", "u1", "assistant", [{"type": "text", "text": "abandoned"}], mid="m0"),
        cc("a1", "u1", "assistant", [{"type": "text", "text": "Running the tests."}], mid="m1"),
        cc("a2", "a1", "assistant", [{"type": "tool_use", "id": "t1", "name": "Bash", "input": {"command": "pytest"}}], mid="m1"),
        cc("a3", "a2", "assistant", [{"type": "tool_use", "id": "t2", "name": "Read", "input": {"file_path": "x.py"}}], mid="m1"),
        cc("r1", "a2", "user", [{"type": "tool_result", "tool_use_id": "t1", "content": "1 failed, 2 passed", "is_error": True}]),
        cc("r2", "a3", "user", [{"type": "tool_result", "tool_use_id": "t2", "content": [{"type": "text", "text": "def f(): ..."}]}]),
        cc("side", "a3", "user", "subagent: look around", isSidechain=True),
        cc("a4", "r2", "assistant", [{"type": "tool_use", "id": "t3", "name": "Edit", "input": {"file_path": "x.py"}}], mid="m2"),
        cc("r3", "a4", "user", [{"type": "tool_result", "tool_use_id": "t3", "content": "Edited x.py"}]),
        cc("a5", "r3", "assistant", [{"type": "thinking", "thinking": "..."}, {"type": "text", "text": "Fixed."}], mid="m3"),
        cc("u2", "a5", "user", "No, you changed the wrong file."),
        cc("err", "u2", "assistant", [{"type": "text", "text": "API Error: overloaded"}], mid="m4", model="<synthetic>"),
        cc("cmd", "err", "user", "<command-name>/compact</command-name>"),
        {"type": "system", "subtype": "compact_boundary", "uuid": "b1", "parentUuid": None,
         "logicalParentUuid": "cmd", "sessionId": "s1", "timestamp": T0},
        cc("sum", "b1", "user", "This session is being continued from a previous conversation...", isCompactSummary=True),
        cc("u3", "sum", "user", "Also use pathlib in the fix"),
        cc("a6", "u3", "assistant", [{"type": "text", "text": "Done."}], mid="m5"),
    ]
    if more:
        lines += [
            cc("u4", "a6", "user", "and add a test"),
            cc("a7", "u4", "assistant", [{"type": "text", "text": "Added."}], mid="m6"),
        ]
    jsonl(tmp_path / "logs/claude/-work-proj/s1.jsonl", lines)
    jsonl(tmp_path / "logs/claude/-work-proj/s1/subagents/agent-1.jsonl",
          [cc("x1", None, "user", "subagent task"), cc("x2", "x1", "assistant", [{"type": "text", "text": "ok"}], mid="mx")])
    return tmp_path / "logs/claude"


def test_a_claude_code_transcript_becomes_one_chat_conversation(tmp_path):
    [conversation] = imports.read("claude-code", claude_session(tmp_path))
    said = [(m["role"], m.get("content"), [c["function"]["name"] for c in m.get("tool_calls", [])])
            for _, m in conversation.turns]
    assert said == [
        ("user", "fix the failing test", []),
        # One response, both parallel calls, each result after its call.
        ("assistant", "Running the tests.", ["Bash", "Read"]),
        ("tool", "Error: 1 failed, 2 passed", []),
        ("tool", "def f(): ...", []),
        ("assistant", "", ["Edit"]),
        ("tool", "Edited x.py", []),
        ("assistant", "Fixed.", []),
        ("user", "No, you changed the wrong file.", []),
        # Through the compaction: one conversation, without the summary.
        ("user", "Also use pathlib in the fix", []),
        ("assistant", "Done.", []),
    ]
    assert conversation.turns[1][1]["model"] == "claude-test"
    assert json.loads(conversation.turns[1][1]["tool_calls"][0]["function"]["arguments"]) == {"command": "pytest"}


def codex_session(tmp_path):
    def item(payload):
        return {"timestamp": T0, "type": "response_item", "payload": payload}

    def says(role, text):
        kind = "output_text" if role == "assistant" else "input_text"
        return item({"type": "message", "role": role, "content": [{"type": kind, "text": text}]})

    return jsonl(tmp_path / "logs/codex/2026/11/01/rollout-2026-11-01T10-00-00-c1.jsonl", [
        {"timestamp": T0, "type": "session_meta", "payload": {"id": "c1", "cwd": "/work/proj"}},
        {"timestamp": T0, "type": "turn_context", "payload": {"model": "codex-test", "cwd": "/work/proj"}},
        says("user", "<environment_context>\n  <cwd>/work/proj</cwd>\n</environment_context>"),
        says("user", "add a retry to fetch()"),
        item({"type": "reasoning", "summary": [], "encrypted_content": "x"}),
        says("assistant", "I'll add tenacity."),
        item({"type": "function_call", "name": "shell", "call_id": "c-1",
              "arguments": json.dumps({"command": ["pip", "install", "tenacity"]})}),
        item({"type": "function_call_output", "call_id": "c-1", "output": "Successfully installed"}),
        says("assistant", "Added a retry."),
        {"timestamp": T0, "type": "event_msg", "payload": {"type": "token_count"}},
        says("user", "use uv add, not pip install"),
        item({"type": "custom_tool_call", "name": "apply_patch", "call_id": "c-2", "input": "*** Begin Patch"}),
        item({"type": "custom_tool_call_output", "call_id": "c-2", "output": "Done"}),
        says("assistant", "Switched to uv."),
    ]).parent.parent.parent.parent


def test_a_codex_rollout_becomes_one_chat_conversation(tmp_path):
    [conversation] = imports.read("codex", codex_session(tmp_path))
    said = [(m["role"], m.get("content"), [c["function"]["name"] for c in m.get("tool_calls", [])])
            for _, m in conversation.turns]
    assert said == [
        ("user", "add a retry to fetch()", []),
        ("assistant", "I'll add tenacity.", ["shell"]),
        ("tool", "Successfully installed", []),
        ("assistant", "Added a retry.", []),
        ("user", "use uv add, not pip install", []),
        ("assistant", "", ["apply_patch"]),
        ("tool", "Done", []),
        ("assistant", "Switched to uv.", []),
    ]
    # Codex writes a command as a list; it is read as the line a person types.
    assert json.loads(conversation.turns[1][1]["tool_calls"][0]["function"]["arguments"]) == {
        "command": "pip install tenacity"
    }
    assert conversation.ident == "c1"
    assert {m.get("model") for _, m in conversation.turns if m["role"] == "assistant"} == {"codex-test"}


def test_plain_messages_from_any_tool(tmp_path):
    path = jsonl(tmp_path / "export.jsonl", [
        {"model": "local-test", "created": 1762000000, "messages": [
            {"role": "system", "content": "You are helpful."},
            {"role": "user", "content": "answer in three bullets at most"},
            {"role": "assistant", "content": "- a\n- b"},
        ]},
        {"messages": "not a list"},
    ])
    [conversation] = imports.read("messages", path)
    assert [m["role"] for _, m in conversation.turns] == ["user", "assistant"]
    assert conversation.turns[0][0] == 1762000000


def test_an_imported_conversation_is_one_session_read_like_a_recorded_one(store, tmp_path):
    conversations = imports.read("claude-code", claude_session(tmp_path))
    assert imports.write(store, conversations, "claude-code") == (1, 4)
    store.reconstruct()
    with store.connect() as db:
        sessions = timeline.sessions(db)
    assert [len(ids) for ids in sessions.values()] == [4]
    assert asyncio.run(reading.read(store, FakeReader())) == 1
    corrections = [s for s in reading.signals(store) if s["type"] == "correction"]
    assert "No, you changed the wrong file." in [s.get("text") for s in corrections]


def test_importing_the_same_logs_again_adds_only_what_is_new(store, tmp_path):
    imports.write(store, imports.read("claude-code", claude_session(tmp_path)), "claude-code")
    assert imports.write(store, imports.read("claude-code", claude_session(tmp_path)), "claude-code") == (0, 0)
    # The session went on after the first import: only its new answer comes in.
    assert imports.write(store, imports.read("claude-code", claude_session(tmp_path, more=True)), "claude-code") == (1, 1)
    store.reconstruct()
    with store.connect() as db:
        assert [len(ids) for ids in timeline.sessions(db).values()] == [5]


def test_imported_turns_are_never_test_moments_or_training_contexts(store, tmp_path):
    """Another model answered them, with another agent's tools: what the user
    said is read, the turns themselves are not measured or trained on."""
    imports.write(store, imports.read("codex", codex_session(tmp_path)), "codex")
    store.record(
        "/v1/chat/completions",
        {"model": "songe/test", "messages": [{"role": "user", "content": "hi"}]},
        {"choices": [{"message": {"role": "assistant", "content": "Hello."}}]},
    )
    store.reconstruct()
    with store.connect() as db:
        assert db.execute("SELECT COUNT(*) FROM steps").fetchone()[0] == 5
    assert [s["action"]["content"] for s in store.active_steps()] == ["Hello."]
    assert store.test_moment_conversations() == []


def test_forget_also_forgets_older_logs(store, tmp_path):
    conversations = imports.read("codex", codex_session(tmp_path))
    imports.write(store, conversations, "codex")
    store.forget()
    with store.connect() as db:
        assert db.execute("SELECT COUNT(*) FROM imports").fetchone()[0] == 0
    # Logs from before the forget stay forgotten when imported again.
    assert imports.write(store, conversations, "codex") == (0, 0)
    found = imports.plan(conversations, forgotten_at=store.get("forgotten_at"))
    assert found["conversations"] == [] and found["forgotten"] == 1


def test_since_leaves_out_older_conversations(tmp_path):
    conversations = imports.read("codex", codex_session(tmp_path))
    assert imports.plan(conversations, since=cli.since_time("2026-12-01"))["too_old"] == 1
    assert len(imports.plan(conversations, since=cli.since_time("30d", now=1762000000))["conversations"]) == 1
    with pytest.raises(ValueError):
        cli.since_time("last week")


def test_the_command_shows_what_it_found_and_imports_on_yes(tmp_path, capsys):
    from songe.config import Config
    from songe.log import Store

    root = tmp_path / "data"
    Config(model=str(tmp_path / "local/model"), public_model="songe/test").save(root)
    logs = codex_session(tmp_path)
    assert cli.main(["--data-dir", str(root), "import", "codex", str(logs), "--yes"]) == 0
    out = capsys.readouterr().out
    assert "conversations  1" in out and "your messages  2" in out and "codex-test 4" in out
    assert "1 conversation imported" in out
    assert cli.main(["--data-dir", str(root), "import", "codex", str(logs), "--yes"]) == 0
    assert "Already imported" in capsys.readouterr().out
    with Store(root).connect() as db:
        assert db.execute("SELECT COUNT(*) FROM exchanges WHERE binding='import:codex'").fetchone()[0] == 4
        # Linked into conversations right away, ready for the next reading;
        # nothing has to pass through the proxy first.
        assert db.execute("SELECT COUNT(*) FROM steps").fetchone()[0] == 4
        assert len(timeline.sessions(db)) == 1
