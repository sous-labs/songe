"""Past conversations from an agent's own logs, as if they had passed through
Songe (`songe import`).

Songe learns from what passes through its proxy. People who used an agent
before installing Songe already have weeks of conversations on disk; this
turns them into the same recordings the proxy makes, so Quick and Deep
Dreams read them like any other session.

Read on this machine only, written only to Songe's own data folder; nothing
is sent anywhere.

Who answered: the turns in these logs were usually answered by another model
(a hosted one, or the same local model behind another agent with other
tools). So what Songe takes from them is what the user said: corrections,
preferences and rules become notes and practice, and the practice is answered
by the user's own model. The logged turns themselves are never test moments
or training contexts (log.NOT_IMPORTED).

Formats:
- `claude-code`: Claude Code transcripts, ~/.claude/projects/<project>/<session>.jsonl
- `codex`: Codex rollouts, ~/.codex/sessions/YYYY/MM/DD/rollout-*.jsonl
- `messages`: any tool's export, one JSON object per line:
  {"messages": [OpenAI chat messages], "model": "...", "created": 1764000000}
"""

import json
import os
import shlex
import time
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

from .steps import digest

FORMATS = ("claude-code", "codex", "messages")


@dataclass
class Conversation:
    source: str
    ident: str
    # (unix time, OpenAI chat message); an assistant message may carry "model".
    turns: list = field(default_factory=list)

    def answers(self):
        return sum(1 for _, m in self.turns if m.get("role") == "assistant")

    def said(self):
        return sum(1 for _, m in self.turns if m.get("role") == "user")


def default_path(fmt, home=None):
    home = Path(home or Path.home())
    if fmt == "claude-code":
        base = Path(os.environ.get("CLAUDE_CONFIG_DIR") or home / ".claude")
        return base / "projects"
    if fmt == "codex":
        return Path(os.environ.get("CODEX_HOME") or home / ".codex") / "sessions"
    return None


def _when(value, default=0.0):
    if isinstance(value, (int, float)):
        return float(value)
    if isinstance(value, str) and value:
        try:
            return datetime.fromisoformat(value.replace("Z", "+00:00")).timestamp()
        except ValueError:
            return default
    return default


def _lines(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        for raw in f:
            raw = raw.strip()
            if not raw:
                continue
            try:
                value = json.loads(raw)
            except ValueError:
                continue
            if isinstance(value, dict):
                yield value


def _files(path, pattern):
    path = Path(path).expanduser()
    if path.is_file():
        return [path]
    return sorted(p for p in path.rglob(pattern) if p.is_file())


# Text an agent puts in the user's place: its own context, commands and
# notices, not something the user said.
CLAUDE_INTERNAL = (
    "<command-name>",
    "<command-message>",
    "<command-args>",
    "<local-command-stdout>",
    "<local-command-stderr>",
    "<system-reminder>",
    "Caveat: The messages below were generated by the user while running local commands",
)
CODEX_INTERNAL = (
    "<environment_context>",
    "<user_instructions>",
    "# AGENTS.md instructions",
    "<permissions instructions>",
    "<turn_aborted>",
    "<user_shell_command>",
)


def _text_blocks(content):
    if isinstance(content, str):
        return content
    parts = []
    for block in content or []:
        if isinstance(block, str):
            parts.append(block)
        elif isinstance(block, dict) and block.get("type") in ("text", "input_text", "output_text"):
            parts.append(block.get("text") or "")
        elif isinstance(block, dict) and block.get("type") in ("image", "input_image"):
            parts.append("[image]")
    return "\n".join(p for p in parts if p)


def _command_text(arguments):
    """Codex's shell tool takes its command as a list (["uv", "add", "x"]);
    agents that go through Songe send one string, which is what Songe reads."""
    if isinstance(arguments, str):
        try:
            parsed = json.loads(arguments)
        except ValueError:
            return arguments
        if not isinstance(parsed, dict):
            return arguments
        arguments = parsed
    if isinstance(arguments, dict) and isinstance(arguments.get("command"), list):
        arguments = dict(arguments)
        arguments["command"] = shlex.join(str(part) for part in arguments["command"])
    return arguments


def _call(call_id, name, arguments):
    arguments = _command_text(arguments)
    if not isinstance(arguments, str):
        arguments = json.dumps(arguments if arguments is not None else {}, ensure_ascii=False)
    return {"id": call_id, "type": "function", "function": {"name": name, "arguments": arguments}}


def _tool_message(call_id, content, error=False):
    text = content if isinstance(content, str) else _text_blocks(content)
    if error and "error" not in text.lower():
        text = "Error: " + text
    return {"role": "tool", "tool_call_id": call_id, "content": text}


# --- Claude Code ------------------------------------------------------------


def _claude_chain(entries):
    """The conversation as the user last left it: walk back from the newest
    entry on the main thread (not a subagent's), through compactions. Turns a
    rewind abandoned are not on it."""
    by_uuid = {e["uuid"]: e for e in entries}
    parents = {e.get("parentUuid") for e in entries}
    leaves = [
        e for e in entries
        if e["uuid"] not in parents
        and e.get("type") in ("user", "assistant")
        and not e.get("isSidechain")
        and not e.get("teamName")
        and not e.get("isMeta")
    ]
    if not leaves:
        return []
    chain, seen = [], set()
    cur = leaves[-1]
    while cur is not None and cur["uuid"] not in seen:
        seen.add(cur["uuid"])
        chain.append(cur)
        parent = cur.get("parentUuid") or cur.get("logicalParentUuid")
        cur = by_uuid.get(parent) if parent else None
    return list(reversed(chain))


def claude_code(path):
    """Claude Code writes one line per content block; the blocks of one model
    response share message.id, and the results of parallel tool calls hang
    off different blocks. Responses are put back together by message.id and
    every result follows its call."""
    for file in _files(path, "*.jsonl"):
        if "subagents" in file.parts:
            continue  # a subagent's own thread: the user did not talk there
        entries = [
            e for e in _lines(file)
            if isinstance(e.get("uuid"), str) and e.get("type") in ("user", "assistant", "system")
        ]
        main = [e for e in entries if not e.get("isSidechain") and not e.get("teamName")]
        by_message, results = {}, {}
        for e in main:
            message = e.get("message") if isinstance(e.get("message"), dict) else {}
            if e.get("type") == "assistant" and message.get("id"):
                by_message.setdefault(message["id"], []).append(e)
            elif e.get("type") == "user" and isinstance(message.get("content"), list):
                for block in message["content"]:
                    if isinstance(block, dict) and block.get("type") == "tool_result":
                        results.setdefault(block.get("tool_use_id"), (e, block))
        conversation = Conversation("claude-code", file.stem)
        done = set()
        for e in _claude_chain(entries):
            message = e.get("message") if isinstance(e.get("message"), dict) else {}
            when = _when(e.get("timestamp"))
            if e.get("type") == "assistant":
                mid = message.get("id")
                if mid in done or message.get("model") == "<synthetic>":
                    continue  # error notices the agent wrote itself
                done.add(mid)
                text, calls = [], []
                for part in by_message.get(mid, [e]):
                    for block in (part.get("message") or {}).get("content") or []:
                        if not isinstance(block, dict):
                            continue
                        if block.get("type") == "text":
                            text.append(block.get("text") or "")
                        elif block.get("type") == "tool_use":
                            calls.append(_call(block.get("id"), block.get("name"), block.get("input")))
                if not text and not calls:
                    continue
                answer = {"role": "assistant", "content": "\n".join(t for t in text if t)}
                if calls:
                    answer["tool_calls"] = calls
                answer["model"] = message.get("model") or ""
                conversation.turns.append((when, answer))
                for call in calls:
                    found = results.get(call["id"])
                    if found:
                        _, block = found
                        conversation.turns.append(
                            (_when(found[0].get("timestamp"), when),
                             _tool_message(call["id"], block.get("content"), block.get("is_error")))
                        )
            elif e.get("type") == "user":
                if e.get("isMeta") or e.get("isCompactSummary"):
                    continue
                content = message.get("content")
                said = _text_blocks(
                    [b for b in content if not (isinstance(b, dict) and b.get("type") == "tool_result")]
                    if isinstance(content, list) else content
                ).strip()
                if said and not said.startswith(CLAUDE_INTERNAL):
                    conversation.turns.append((when, {"role": "user", "content": said}))
        if conversation.answers():
            yield conversation


# --- Codex ------------------------------------------------------------------

CODEX_CALLS = ("function_call", "custom_tool_call", "local_shell_call")
CODEX_OUTPUTS = ("function_call_output", "custom_tool_call_output")


def _codex_output(value):
    if isinstance(value, dict):
        value = value.get("content", value.get("output", value))
    if isinstance(value, list):
        return _text_blocks(value)
    return value if isinstance(value, str) else json.dumps(value, ensure_ascii=False)


def _close(conversation, state):
    """The response collected so far, as one assistant message."""
    pending = state.pop("pending", None)
    if pending and (pending.get("content") or pending.get("tool_calls")):
        pending["model"] = state.get("model", "")
        conversation.turns.append((state.get("at", 0.0), pending))


def _open(state, when):
    if "pending" not in state:
        state["pending"], state["at"] = {"role": "assistant", "content": ""}, when
    return state["pending"]


def codex(path):
    """Codex records each item of a response (text, tool calls) on its own
    line; a run of them with nothing from the user or a tool in between is
    one model response."""
    for file in _files(path, "*.jsonl"):
        conversation = Conversation("codex", file.stem)
        state = {"model": ""}
        for line in _lines(file):
            kind = line.get("type")
            payload = line.get("payload") if isinstance(line.get("payload"), dict) else None
            when = _when(line.get("timestamp"))
            if kind == "session_meta" and payload:
                conversation.ident = str(payload.get("id") or conversation.ident)
                state["model"] = payload.get("model") or state["model"]
                continue
            if kind == "turn_context" and payload:
                state["model"] = payload.get("model") or state["model"]
                continue
            if kind == "response_item" and payload:
                item = payload
            elif kind in ("message", *CODEX_CALLS, *CODEX_OUTPUTS, "reasoning"):
                item = line  # rollouts written before the line wrapper
            else:
                continue
            itype = item.get("type")
            if itype == "message" and item.get("role") == "assistant":
                pending = _open(state, when)
                text = _text_blocks(item.get("content"))
                pending["content"] = "\n".join(t for t in (pending["content"], text) if t)
            elif itype in CODEX_CALLS:
                if itype == "function_call":
                    call = _call(item.get("call_id"), item.get("name"), item.get("arguments"))
                elif itype == "custom_tool_call":
                    call = _call(item.get("call_id"), item.get("name"), {"input": item.get("input")})
                else:
                    action = item.get("action") or {}
                    call = _call(item.get("call_id") or item.get("id"), "shell",
                                 {"command": action.get("command")})
                _open(state, when).setdefault("tool_calls", []).append(call)
            elif itype in CODEX_OUTPUTS:
                _close(conversation, state)
                conversation.turns.append(
                    (when, _tool_message(item.get("call_id"), _codex_output(item.get("output"))))
                )
            elif itype == "message" and item.get("role") == "user":
                _close(conversation, state)
                said = _text_blocks(item.get("content")).strip()
                if said and not said.startswith(CODEX_INTERNAL):
                    conversation.turns.append((when, {"role": "user", "content": said}))
        _close(conversation, state)
        if conversation.answers():
            yield conversation


# --- Plain messages ---------------------------------------------------------


def messages(path):
    for file in _files(path, "*.jsonl"):
        for number, line in enumerate(_lines(file)):
            history = line.get("messages")
            if not isinstance(history, list):
                continue
            when = _when(line.get("created"), time.time())
            conversation = Conversation("messages", str(line.get("id") or f"{file.stem}:{number}"))
            for message in history:
                if not isinstance(message, dict) or message.get("role") not in ("user", "assistant", "tool"):
                    continue
                message = dict(message)
                if message["role"] == "assistant":
                    message.setdefault("model", line.get("model") or "")
                conversation.turns.append((when, message))
            if conversation.answers():
                yield conversation


READERS = {"claude-code": claude_code, "codex": codex, "messages": messages}


def read(fmt, path):
    return list(READERS[fmt](path))


# --- Into Songe's recordings -------------------------------------------------


def _tools(conversation):
    """A minimal schema for each tool the conversation used: the logs keep
    the calls, not the agent's tool list."""
    names = sorted({
        c["function"]["name"]
        for _, m in conversation.turns
        for c in m.get("tool_calls") or []
        if c.get("function", {}).get("name")
    })
    return [
        {"type": "function", "function": {"name": n, "description": "", "parameters": {"type": "object"}}}
        for n in names
    ]


def exchanges(conversation):
    """(time, request, response) for each answer, as the proxy records them:
    the request carries the whole history before the answer."""
    tools = _tools(conversation)
    history = []
    for when, message in conversation.turns:
        if message.get("role") == "assistant":
            answer = {k: v for k, v in message.items() if k != "model"}
            model = message.get("model") or ""
            request = {"model": model, "messages": list(history)}
            if tools:
                request["tools"] = tools
            response = {
                "object": "chat.completion",
                "model": model,
                "choices": [{
                    "index": 0,
                    "message": answer,
                    "finish_reason": "tool_calls" if answer.get("tool_calls") else "stop",
                }],
            }
            yield when, request, response
            history.append(answer)
        else:
            history.append(message)


def plan(conversations, since=None, forgotten_at=None):
    """What an import would bring in, before writing anything."""
    kept, too_old, forgotten, models = [], 0, 0, {}
    for conversation in conversations:
        last = max((t for t, _ in conversation.turns), default=0)
        if since is not None and last < since:
            too_old += 1
            continue
        if forgotten_at is not None and last <= forgotten_at:
            forgotten += 1
            continue
        kept.append(conversation)
        for _, m in conversation.turns:
            if m.get("role") == "assistant" and m.get("model"):
                models[m["model"]] = models.get(m["model"], 0) + 1
    return {
        "conversations": kept,
        "answers": sum(c.answers() for c in kept),
        "said": sum(c.said() for c in kept),
        "too_old": too_old,
        "forgotten": forgotten,
        "models": dict(sorted(models.items(), key=lambda kv: -kv[1])),
    }


def write(store, conversations, fmt):
    """Recordings for these conversations; turns already imported are passed
    over. Returns (conversations with something new, turns added)."""
    binding = f"import:{fmt}"
    touched, added = 0, 0
    for conversation in conversations:
        new = 0
        for when, request, response in exchanges(conversation):
            key = digest({"messages": request["messages"], "answer": response["choices"][0]["message"]})
            if store.record(
                "/v1/chat/completions", request, response, 200, True,
                binding=binding, started=when, import_key=key,
            ) is not None:
                new += 1
        touched += bool(new)
        added += new
    if added:
        store.event(
            "record",
            f"{touched} conversation{'s' if touched != 1 else ''} imported from {fmt}"
            f" · {added} answer{'s' if added != 1 else ''}",
            model_id="",
        )
    return touched, added
